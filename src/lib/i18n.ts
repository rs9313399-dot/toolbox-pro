export type TranslationKey = keyof typeof translations;

// Helper to get a translation value
export function t(section: string, key: string, lang: Lang): string {
  const sectionData = (translations as any)[section];
  if (!sectionData) return key;
  const keyData = sectionData[key];
  if (!keyData) return key;
  return keyData[lang] || keyData.en || key;
}

// Get all translations
export function getTranslations() {
  return translations;
}

export default translations;
